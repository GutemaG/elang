import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'

import { FakeServer } from '../test/fakeServer'
import { idTokenFor } from '../test/fixtures'
import { renderApp, withStoredSession } from '../test/renderApp'
import type { AudioExport, AudioFile, AudioLibrary, AudioUse } from './api'

vi.mock('../auth/GoogleButton', () => ({
  GoogleButton: ({ onCredential }: { onCredential: (token: string) => void }) => (
    <button type="button" onClick={() => onCredential(idTokenFor('admin@example.com'))}>
      Sign in with Google
    </button>
  ),
}))

const ME = '/api/v1/admin/me'
const LIB = '/api/v1/admin/audio-files'
const SUPER = { email: 'admin@example.com', role: 'super_admin', is_owner: true, course_ids: null }
const HELPER = { email: 'admin@example.com', role: 'course_admin', is_owner: false, course_ids: ['course-1'] }

const EX_USE: AudioUse = {
  place: 'exercise',
  language: 'am',
  admin_path: '/courses/course-1/lessons/lesson-1/exercises/ex-2',
  course_id: 'course-1',
  course_title: 'English to Amharic',
  section: 'Greetings',
  skill: 'Hello',
  lesson: 'Saying hi',
  exercise_id: 'ex-2',
  exercise_number: 2,
  exercise_type: 'listening',
  prompt: 'What did you hear?',
  text: null,
  english: null,
  letter: null,
}

function file(key: string, extra: Partial<AudioFile> = {}): AudioFile {
  return {
    key,
    url: `https://pub.example/${key}`,
    size: 2048,
    uploaded_at: '2026-10-01T08:00:00Z',
    language: 'am',
    source: 'recorded',
    status: 'unused',
    can_trash: true,
    uses: [],
    ...extra,
  }
}

const USED = 'am/lesson-1/aaaaaaaaaaaa.m4a'
const OLD = 'am/lesson-1/gen-am-meron-bbbbbbbbbbbb.m4a'
const NEW = 'am/lesson-1/cccccccccccc.m4a'

let server: FakeServer
let library: AudioLibrary

beforeEach(() => {
  withStoredSession()
  library = {
    storage: 'r2',
    totals: { files: 3, bytes: 6144, in_use: 1, unused: 2, missing: 1, trash: 1, trash_bytes: 100 },
    files: [
      file(NEW, { can_trash: false }),
      file(USED, { status: 'in_use', can_trash: false, uses: [EX_USE] }),
      file(OLD, { source: 'generated' }),
    ],
    missing: [{ key: 'am/lesson-1/gone.m4a', url: 'https://pub.example/gone', uses: [{ ...EX_USE, exercise_number: 4 }] }],
    trash: [{ key: 'trash/am/old.m4a', original_key: 'am/old.m4a', size: 100, moved_at: '2026-10-12T08:00:00Z' }],
    external_links: 2,
    courses: [{ id: 'course-1', title: 'English to Amharic', learning_language: 'am' }],
  }
  server = new FakeServer()
    .install()
    .on('GET', ME, { body: SUPER })
    .on('GET', LIB, () => ({ body: library }))
})

const main = () => within(screen.getByRole('main'))
const row = (key: string) => within(main().getByText(key).closest('li')!)

describe('the audio library', () => {
  it('is in Configuration for a super admin only', async () => {
    renderApp('/')
    expect(await screen.findByRole('link', { name: 'Audio library' })).toBeInTheDocument()
  })

  it('sends a course admin back to the workspace', async () => {
    server.on('GET', ME, { body: HELPER }).on('GET', '/api/v1/admin/courses', { body: { courses: [] } })
    renderApp('/audio-library')

    expect(await screen.findByRole('heading', { name: 'Courses' })).toBeInTheDocument()
    expect(screen.queryByRole('link', { name: 'Audio library' })).not.toBeInTheDocument()
  })

  it('lists each file with its status, source and uses, and opens a use', async () => {
    renderApp('/audio-library')

    expect(await screen.findByRole('heading', { name: 'Audio library' })).toBeInTheDocument()
    await screen.findByText(USED)
    const used = row(USED)
    expect(used.getByText('In use')).toBeInTheDocument()
    expect(
      used.getByText('English to Amharic › Greetings › Saying hi › Exercise 2 (Listening)'),
    ).toBeInTheDocument()
    expect(used.getByRole('link', { name: 'Open' })).toHaveAttribute('href', EX_USE.admin_path)
    expect(used.queryByRole('checkbox')).not.toBeInTheDocument()
    expect(row(OLD).getByText(/Generated by Addis AI/)).toBeInTheDocument()
    expect(row(NEW).getByText(/Less than a day old/)).toBeInTheDocument()
    expect(screen.getByText(/2 links point to audio elsewhere/)).toBeInTheDocument()
  })

  it('plays one file at a time', async () => {
    const play = vi.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue(undefined)
    vi.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {})
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('button', { name: `Play ${USED}` }))

    expect((play.mock.contexts.at(-1) as HTMLAudioElement).src).toBe(`https://pub.example/${USED}`)
    expect(screen.getByRole('button', { name: `Stop ${USED}` })).toBeInTheDocument()
  })

  it('filters by status', async () => {
    renderApp('/audio-library')
    await screen.findByText(USED)

    await userEvent.selectOptions(screen.getByLabelText('Status'), 'Not used')

    expect(main().queryByText(USED)).not.toBeInTheDocument()
    expect(main().getByText(OLD)).toBeInTheDocument()
  })

  it('moves the files nothing uses to the trash after asking', async () => {
    server.on('POST', `${LIB}/trash`, (call) => {
      library = { ...library, files: library.files.filter((f) => f.key !== OLD) }
      return { body: { count: (call.body as { keys: string[] }).keys.length } }
    })
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('button', { name: 'Select all not used (1)' }))
    expect(row(OLD).getByRole('checkbox')).toBeChecked()
    await userEvent.click(screen.getByRole('button', { name: 'Move to trash' }))
    const dialog = within(screen.getByRole('dialog', { name: 'Move 1 file to the trash?' }))
    expect(dialog.getByText(/2\.0 KB\. Nothing uses them/)).toBeInTheDocument()
    await userEvent.click(dialog.getByRole('button', { name: 'Move to trash' }))

    expect(server.callsTo('POST', `${LIB}/trash`)[0]!.body).toEqual({ keys: [OLD] })
    await waitFor(() => expect(main().queryByText(OLD)).not.toBeInTheDocument())
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('keeps a refusal in the dialog', async () => {
    server.on('POST', `${LIB}/trash`, {
      status: 409,
      body: { error_code: 'audio_file_in_use', message: 'Only files nothing uses can go', details: { keys: [OLD] } },
    })
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('checkbox', { name: `Select ${OLD}` }))
    await userEvent.click(screen.getByRole('button', { name: 'Move to trash' }))
    const dialog = within(screen.getByRole('dialog'))
    await userEvent.click(dialog.getByRole('button', { name: 'Move to trash' }))

    expect(await dialog.findByRole('alert')).toHaveTextContent('Only files nothing uses can go')
  })

  it('shows missing files with where to fix them', async () => {
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('button', { name: 'Missing (1)' }))

    const missing = row('am/lesson-1/gone.m4a')
    expect(missing.getByText(/Exercise 4/)).toBeInTheDocument()
    expect(missing.getByRole('link', { name: 'Open' })).toBeInTheDocument()
  })

  it('restores from the trash, and deletes for good after a warning', async () => {
    server
      .on('POST', `${LIB}/trash/restore`, { body: { count: 1 } })
      .on('POST', `${LIB}/trash/delete`, { body: { count: 1 } })
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('button', { name: 'Trash (1)' }))
    await userEvent.click(screen.getByRole('checkbox', { name: 'Select am/old.m4a' }))
    await userEvent.click(screen.getByRole('button', { name: 'Restore' }))
    expect(server.callsTo('POST', `${LIB}/trash/restore`)[0]!.body).toEqual({ keys: ['trash/am/old.m4a'] })

    await userEvent.click(screen.getByRole('checkbox', { name: 'Select am/old.m4a' }))
    await userEvent.click(screen.getByRole('button', { name: 'Delete for good' }))
    const dialog = within(screen.getByRole('dialog', { name: 'Delete 1 file for good?' }))
    expect(dialog.getByText(/can’t be undone/)).toBeInTheDocument()
    await userEvent.click(dialog.getByRole('button', { name: 'Delete for good' }))
    expect(server.callsTo('POST', `${LIB}/trash/delete`)[0]!.body).toEqual({ keys: ['trash/am/old.m4a'] })
  })
})

describe('the backup export', () => {
  let saved: Blob | null

  beforeEach(() => {
    saved = null
    URL.createObjectURL = vi.fn((blob: Blob) => {
      saved = blob
      return 'blob:backup'
    })
    URL.revokeObjectURL = vi.fn()
    vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
  })

  const plan: AudioExport = {
    name: 'buna-audio-english-to-amharic-2026-10-13',
    files: [
      { zip_path: 'english-to-amharic/ex02-listening-aaaaaa.m4a', key: USED, size: 3, download_url: 'https://r2.example/a' },
      { zip_path: 'sounds/am/h-01-ha-sound-cccccc.m4a', key: NEW, size: 3, download_url: 'https://r2.example/b' },
    ],
    rows: [
      {
        zip_path: 'english-to-amharic/ex02-listening-aaaaaa.m4a',
        status: 'in_use',
        key: USED,
        url: 'u',
        size: 3,
        uploaded_at: null,
        use: EX_USE,
      },
      { zip_path: 'sounds/am/h-01-ha-sound-cccccc.m4a', status: 'in_use', key: NEW, url: 'u', size: 3, uploaded_at: null, use: null },
    ],
  }

  function readBlob(blob: Blob): Promise<string> {
    return new Promise((resolve) => {
      const reader = new FileReader()
      reader.onload = () => resolve(new TextDecoder().decode(reader.result as ArrayBuffer))
      reader.readAsArrayBuffer(blob)
    })
  }

  it('builds the ZIP in the browser from the signed links, with the manifest', async () => {
    server
      .on('GET', `${LIB}/export`, { body: plan })
      .on('GET', '/a', { body: new Blob(['AAA']) })
      .on('GET', '/b', { status: 403 })
    renderApp('/audio-library')

    await userEvent.click(await screen.findByRole('button', { name: 'Export backup' }))
    const dialog = within(screen.getByRole('dialog', { name: 'Export audio backup' }))
    await userEvent.selectOptions(dialog.getByLabelText('What to export'), 'English to Amharic (with its Sounds)')
    await userEvent.click(dialog.getByLabelText('Include files nothing uses'))
    await userEvent.click(dialog.getByRole('button', { name: 'Export' }))

    expect(await dialog.findByRole('status')).toHaveTextContent(
      'Saved buna-audio-english-to-amharic-2026-10-13.zip: 1 file',
    )
    expect(dialog.getByRole('alert')).toHaveTextContent('1 file could not be downloaded')
    expect(server.callsTo('GET', `${LIB}/export`)[0]!.query).toBe('?course_id=course-1&include_unused=true')
    const download = server.callsTo('GET', '/a')[0]!
    expect(download.token).toBeNull()

    const zip = await readBlob(saved!)
    expect(zip).toContain('buna-audio-english-to-amharic-2026-10-13/english-to-amharic/ex02-listening-aaaaaa.m4a')
    expect(zip).toContain('AAA')
    expect(zip).toContain('buna-audio-english-to-amharic-2026-10-13/manifest.csv')
    expect(zip).toContain('download_failed')
    expect(zip).not.toContain('buna-audio-english-to-amharic-2026-10-13/sounds/')
  })
})
